    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                         
    // 1. Get the customer name and product name the text fields
                                      
    
  
    String customerName = jTextField1.getText();
     String product = jTextField2.getText();
    
    // 2. Get the price and convert it to an integer
   
   int productPrice = Integer.parseInt(jTextField3.getText());
    
    // 3. Calculate VAT (15%) and commission (if 10% of product price)

     int vat = (int) (productPrice * 0.15); 
     int commission = (int) (productPrice * 0.10);
    
    // 4. Calculate the total (Price + VAT)
    int total = productPrice + vat;
    
    // 5. Create the report string
    String report = "Customer Name: " + customerName + "\n" +
                    "Product: " + product + "\n" +
                    "Price: R" + productPrice + "\n" +
                    "VAT (15%): R" + vat + "\n" +
                    "Commission: R" + commission + "\n" +
                    "Total: R" + total;
                    
    // 6. Print the completed report to the console
    System.out.println(report);
} 
          

